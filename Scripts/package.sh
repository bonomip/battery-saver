#!/bin/zsh
set -euo pipefail
cd "${0:A:h:h}"
export CLANG_MODULE_CACHE_PATH="$PWD/.build/module-cache"
export SWIFTPM_MODULECACHE_OVERRIDE="$PWD/.build/module-cache"
swift build --disable-sandbox -c release
app="$PWD/dist/Battery Saver.app"
mkdir -p "$app/Contents/MacOS" "$app/Contents/Resources" "$app/Contents/Helpers"
/usr/bin/install -m 755 .build/release/BatterySaver "$app/Contents/MacOS/BatterySaver"
/usr/bin/install -m 755 .build/release/battery-saver-helper "$app/Contents/Helpers/battery-saver-helper"
cp Resources/Info.plist "$app/Contents/Info.plist"
cp Resources/AppIcon.icns "$app/Contents/Resources/"
cp Resources/local.paolo.battery-saver.plist "$app/Contents/Resources/"
cp Resources/install-helper.sh "$app/Contents/Resources/"
cp Scripts/uninstall.sh "$app/Contents/Resources/uninstall-helper.sh"
/usr/bin/codesign --force --sign - "$app/Contents/Helpers/battery-saver-helper"
/usr/bin/codesign --force --sign - "$app"
/usr/bin/codesign --verify --deep --strict "$app"
/usr/bin/plutil -lint "$app/Contents/Info.plist"
print "Built: $app"
